#include <iostream>

int main(){

    int a = 5;
    int b = 2;

    std::cout << "Addition: " << (a + b) << std::endl; // 7
    std::cout << "Subtraction: " << (a - b) << std::endl; // 3
    std::cout << "Multiplication: " << (a * b) << std::endl; // 10
    std::cout << "Division: " << (a / b) << std::endl; // 2
    std::cout << "Modulus: " << (a % b) << std::endl; // 1

    return 0;
}